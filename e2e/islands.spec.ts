import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/demos/')
})

test('every interactive demo shares the page Theme and portal roots', async ({ page }) => {
  await expect(page.locator('[data-is-root-theme="true"]')).toHaveCount(1)
  await expect(page.locator('#foldkit-portal-root')).toHaveCount(1)
  await expect(page.locator('[data-island]')).toHaveCount(6)
})
test('TextField input updates its Foldkit model and output', async ({ page }) => {
  const controls = page.locator('[data-island="controls"]')
  await controls.getByLabel('Email address').fill('hello@example.com')
  await expect(controls.locator('[data-testid="field-value"]')).toHaveText('Current value: hello@example.com')
})

test('Select opens its popover and commits Blue', async ({ page }) => {
  const select = page.locator('[data-island="select"]')
  await select.getByRole('combobox', { name: 'docs-color-select' }).click()
  await expect(page.locator('#foldkit-portal-root').getByRole('option', { name: 'Blue' })).toBeVisible()
  await page.locator('#foldkit-portal-root').getByRole('option', { name: 'Blue' }).click()
  await expect(select.locator('[data-selected-value="blue"]')).toContainText('Selected color: blue')
})

test('Dialog closes with Escape and returns focus to its trigger', async ({ page }) => {
  const trigger = page.getByRole('button', { name: 'Open dialog' })
  await trigger.click()
  const dialog = page.getByRole('dialog', { includeHidden: true })
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
})

test('Tabs respond to arrow keys and expose the active panel', async ({ page }) => {
  const overview = page.getByRole('tab', { name: 'Overview' })
  await overview.focus()
  await page.keyboard.press('ArrowRight')
  const details = page.getByRole('tab', { name: 'Details' })
  await expect(details).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('tabpanel')).toContainText('details panel')
})

test('DataTable selection updates its model output', async ({ page }) => {
  const table = page.locator('[data-island="table"]')
  await table.getByRole('checkbox').nth(1).check()
  await expect(table.getByText('1 rows selected')).toBeVisible()
})

test('Theme controls update the shared Theme generated by Themes.view', async ({ page }) => {
  const root = page.locator('[data-is-root-theme="true"]')
  await page.locator('[data-island="theme-panel"]').getByLabel('Accent color').selectOption('jade')
  await expect(root).toHaveAttribute('data-accent-color', 'jade')
  await page.locator('[data-island="theme-panel"]').getByLabel('Appearance').selectOption('dark')
  await expect(root).toHaveAttribute('class', /dark/)
  await expect(page.locator('[data-is-root-theme="true"]')).toHaveCount(1)
})

test('mobile navigation remains usable without a fixed-height page or horizontal overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 740 })
  await page.reload()
  await expect(page.getByText('Documentation navigation')).toBeVisible()
  await page.getByText('Documentation navigation').click()
  await expect(page.getByRole('link', { name: 'Getting started' }).first()).toBeVisible()
  const dimensions = await page.evaluate(() => ({ width: document.documentElement.scrollWidth, viewport: window.innerWidth, height: document.documentElement.scrollHeight }))
  expect(dimensions.width).toBeLessThanOrEqual(dimensions.viewport)
  expect(dimensions.height).toBeGreaterThan(740)
})
